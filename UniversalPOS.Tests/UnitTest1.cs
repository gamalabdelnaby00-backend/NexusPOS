        private static Product CreateProduct(
            string name = "Keyboard",
            decimal price = 500m,
            string barcode = "KB001",
            int categoryId = 1)
        {
            var product = new Product(name, price, barcode, categoryId);

            // Simulate an ID generated by the database.
            typeof(Product)
                .GetProperty(nameof(Product.Id))!
                .SetValue(product, 1);

            return product;
        }

